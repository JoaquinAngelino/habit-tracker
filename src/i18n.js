export const LANGUAGES = Object.keys(STRINGS);

let current = "en";

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : "en";
  if (typeof document !== "undefined") document.documentElement.lang = current;
  return current;
}

export const getLanguage = () => current;

// With a `count`, keys that have `_one`/`_other` forms pick the matching one.
export function t(key, vars = {}) {
  const table = STRINGS[current];
  const form = vars.count == null ? null : `${key}_${vars.count === 1 ? "one" : "other"}`;
  const text = (form && (table[form] ?? STRINGS.en[form])) ?? table[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  // Only for hints written in this file, never for user input.
  root.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  });
  document.title = t("title");
}
